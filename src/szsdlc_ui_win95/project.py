"""One szsdlc project, read through szsdlc itself and shaped for the viewer.

Nothing here re-implements szsdlc. Backend resolution, the merged and validated
config, the entity store, the relation graph and the derived attributes all come
from the library; this module only turns them into the JSON the browser renders
from. The centrepiece is the **schema descriptor**: every type's traits, fields,
workflow and relations. The frontend renders from it alone and never names a type.
"""

from __future__ import annotations

import dataclasses
import datetime as _dt
import os
import re
import threading
from pathlib import Path

import szsdlc
from szsdlc import backend as sz_backend
from szsdlc import config as sz_config
from szsdlc import errors as sz_errors
from szsdlc import graph as sz_graph
from szsdlc import model as sz_model
from szsdlc import roadmap as sz_roadmap

from . import locations
from .documents import Roots, jsonify, references
from .errors import ProjectError, UnsentChanges

GENERATED_MARK = "GENERATED by szsdlc"
SKIP_DIRS = frozenset({".git", "node_modules", "__pycache__", ".venv"})
FIELD_KINDS = {"date": "date", "datetime": "date", "text": "text", "string": "string", "integer": "number",
               "number": "number", "float": "number", "boolean": "bool", "bool": "bool", "list": "list",
               "array": "list", "ref": "ref", "url": "url"}


__all__ = ["Project", "ProjectError"]


def norm_id(ref) -> str | None:
    """`wi-42` and `WI-0042` both become `WI-42`: lookup ignores case and padding."""
    m = re.fullmatch(r"\s*([A-Za-z][A-Za-z0-9]*)-0*(\d+)\s*", str(ref))
    return f"{m.group(1).upper()}-{int(m.group(2))}" if m else None


def pluralize(title: str) -> str:
    if title.endswith("is"):  # hypothesis -> hypotheses
        return title[:-2] + "es"
    if title.endswith("y") and title[-2:-1] not in "aeiou":
        return title[:-1] + "ies"
    return title + ("es" if title.endswith(("s", "x", "ch", "sh")) else "s")


def plain(value):
    """A derived value as JSON: dataclasses become objects, keeping their computed properties."""
    if dataclasses.is_dataclass(value) and not isinstance(value, type):
        out = {f.name: plain(getattr(value, f.name)) for f in dataclasses.fields(value)}
        for prop in ("percent", "complete", "remaining"):
            if isinstance(getattr(type(value), prop, None), property):
                out[prop] = getattr(value, prop)
        return out
    if isinstance(value, (list, tuple)):
        return [plain(v) for v in value]
    return jsonify(value)


class Project:
    """A project the viewer serves. Reloads itself when its files change."""

    def __init__(self, location, asset_root: Path | None = None, excludes=(), *, update: bool = True):
        """Open the project at `location`: a folder here, or a place a backend keeps one (a git URL).

        The project sdlc store dir is materialized if it is not on this computer
        yet, and, when `update` is set, brought up to date if that is safe.
        """
        resolved = locations.resolve(location)
        self.location = resolved.location
        self.remote = resolved.start is None
        self.backend = resolved.backend
        self.relocated = sz_backend.relocates(self.backend)
        self.start = resolved.start or resolved.root
        if asset_root is None and self.relocated and resolved.start is not None:
            # Records kept elsewhere describe the folder the viewer was pointed at.
            asset_root = locations.asset_root_of(resolved.start)
        self.update_warning = locations.bring_up_to_date(self.backend) if update else None
        #: The project sdlc root: the directory holding `.szsdlc/` and the records.
        self.sdlc_root = resolved.root
        #: The local directory the sdlc backend reads and writes; the sdlc root is
        #: inside it, and two projects can share one (a clone, two subdirectories).
        self.sdlc_store_dir = Path(locations.sdlc_store_dir(self.backend)).resolve()
        #: The project asset root: the code and other assets the project describes.
        self.asset_root = Path(asset_root).resolve() if asset_root else None
        self.roots = Roots(self.sdlc_root, self.asset_root)
        self.excludes = SKIP_DIRS | set(excludes)
        self.load_error: str | None = None
        self._lock = threading.RLock()
        try:
            self._load()
        except sz_errors.SzsdlcError as err:
            raise ProjectError(str(err)) from None
        self._stamp = self._fingerprint()

    # -- loading -------------------------------------------------------------
    def _fingerprint(self):
        count, latest = 0, 0.0
        for root, dirs, files in os.walk(self.sdlc_root):
            dirs[:] = [d for d in dirs if d not in self.excludes and (not d.startswith(".") or d == ".szsdlc")]
            for name in files:
                try:
                    latest = max(latest, os.stat(os.path.join(root, name)).st_mtime_ns)
                except OSError:
                    pass
                count += 1
        return count, latest

    def refresh(self) -> None:
        """Reload if anything changed. A failed reload keeps the last good model and reports why."""
        stamp = self._fingerprint()
        if stamp == self._stamp:
            return
        with self._lock:
            try:
                self._load()
                self.load_error = None
            except Exception as err:  # noqa: BLE001 - shown to the user, never raised into a request
                self.load_error = f"{type(err).__name__}: {err}"
            self._stamp = stamp

    def refresh_from_backend(self, replace: bool = False) -> dict:
        """Take the sdlc backend's latest, then reload. Never sends anything.

        szsdlc's `refresh` replaces local state that differs without asking, so
        the asking is done here: unless `replace` is set, a copy with unsent
        changes is left untouched and `UnsentChanges` is raised. A project kept
        in a folder here has nothing to take, so this only re-reads its files.
        """
        if not replace and locations.has_unsent_changes(self.backend):
            raise UnsentChanges(
                "This copy has unsent changes. "
                "Refreshing replaces them with the latest; szsdlc keeps what it replaces.")
        report = locations.refresh(self.backend)
        if not report.ok:
            raise ProjectError(f"Could not refresh from its sdlc backend: {report.problem}"
                               + (f" Fix: {report.fix}" if report.fix else ""))
        stamp = self._fingerprint()
        with self._lock:
            # Background refreshes run every minute; when nothing arrived and no
            # file changed, there is nothing to load again.
            if report.incoming or stamp != self._stamp or self.load_error:
                try:
                    self._load()
                    self.load_error = None
                except Exception as err:  # noqa: BLE001 - shown to the user, never raised into a request
                    self.load_error = f"{type(err).__name__}: {err}"
            self._stamp = stamp
            self.update_warning = None
        return {"arrived": bool(report.incoming), "replaced": bool(report.replaced), "note": report.note}

    def _load(self) -> None:
        cfg = sz_config.load(self.sdlc_root)
        store = sz_model.load_all(cfg)
        graph = sz_graph.build(cfg, store)
        by_key = {norm_id(e.id.text): e for e in store}
        children: dict[str, list] = {}
        incoming: dict[str, list[tuple[str, str]]] = {}
        for e in store:
            for kind, targets in e.relations.items():
                for target in targets:
                    key = norm_id(target)
                    if key:
                        incoming.setdefault(key, []).append((kind, e.id.text))
            parent = e.parent()  # a method in szsdlc, not a property
            if parent and norm_id(parent):
                children.setdefault(norm_id(parent), []).append(e.id.text)
        roadmaps, placement = [], {}
        for name, rm in sz_roadmap.load_all(cfg).items():
            spec = cfg.roadmaps[name]
            horizons = [{"name": h, "items": list(rm.entries(h))} for h in spec.horizons]
            roadmaps.append({"name": name, "title": spec.title, "path": self._rel(cfg.roadmap_path(name)), "horizons": horizons})
            for hz in horizons:
                for position, item in enumerate(hz["items"], 1):
                    placement.setdefault(norm_id(item), {"roadmap": name, "horizon": hz["name"], "position": position})
        # Publish the new model in one step, so a concurrent request sees old or new, never half.
        (self.cfg, self.store_model, self.graph, self.by_key, self.children, self.incoming,
         self.roadmaps, self.placement) = (cfg, store, graph, by_key, children, incoming, roadmaps, placement)
        self.by_path = {self._rel(e.path): e for e in store if e.layout != "section"}
        self.schema = self._schema()
        self.store_docs = self._store_documents()

    def _rel(self, p) -> str:
        p = Path(p)
        try:
            return p.resolve().relative_to(self.sdlc_root).as_posix()
        except ValueError:
            return p.as_posix()

    def _owned(self, f: Path) -> bool:
        """True when `f` belongs to this store, not to a project nested inside it."""
        for parent in f.parents:
            if parent == self.sdlc_root:
                return True
            if (parent / ".szsdlc" / "config.yml").is_file():
                return False
        return False

    # -- the schema descriptor ----------------------------------------------
    def _schema(self) -> dict:
        cfg = self.cfg
        prefix_of = {t.name: t.prefix for t in cfg.entity_types.values()}
        types = []
        for t in cfg.entity_types.values():
            ents = [e for e in self.store_model if e.type.name == t.name]
            used: dict[str, int] = {}
            for e in ents:
                used[str(e.status)] = used.get(str(e.status), 0) + 1
            types.append({
                "key": t.prefix, "prefix": t.prefix, "name": t.name, "label": t.title, "plural": pluralize(t.title),
                "dir": t.dir, "layouts": list(t.layouts),
                "flags": {f: t.flag(f) for f in sz_config.CAPABILITY_FLAGS},
                "flag_source": {f: "config" for f in sz_config.CAPABILITY_FLAGS},
                "fields": [{"name": n, "kind": FIELD_KINDS.get(f.type, "string"), "type": f.type, "required": f.required,
                            "enum": list(f.enum) if f.enum else None, "default": jsonify(f.default),
                            "description": f.description} for n, f in t.fields.items()],
                "workflow": {"ordered": True, "initial": t.workflow.initial, "terminal_source": "config", "statuses": [
                    {"name": n, "count": used.get(n, 0), "terminal": s.terminal, "abandoned": s.abandoned,
                     "to": list(s.to), "requires_artifact": list(s.requires_artifact),
                     "requires_tasks_complete": s.requires_tasks_complete, "description": s.description,
                     "source": "config"} for n, s in t.workflow.states.items()]},
                "artifacts": list(t.artifacts), "progress_artifact": t.progress_artifact,
                "journal_artifact": t.journal_artifact,
                "derived": [{"name": d.name, "kind": d.kind, "relation": d.relation, "description": d.description}
                            for d in t.derived.values()],
                "relations_out": [r.name for r in cfg.relations_from(t.name)],
                "count": len(ents),
            })
        relations = [{"name": r.name, "inverse": r.inverse, "cardinality": r.cardinality, "acyclic": r.acyclic,
                      "description": r.description,
                      "source_types": [prefix_of[x] for x in r.source_types if x in prefix_of],
                      "target_types": [prefix_of[x] for x in (r.target_types or ()) if x in prefix_of]}
                     for r in cfg.relations.values()]
        # Which relation blocks is not yet a szsdlc config key (`szsdlc next`
        # hard-codes "depends_on"). Prefer a declared key, then that convention.
        declared = cfg.data.get("dependency_relation")
        dependency = declared or ("depends_on" if "depends_on" in cfg.relations else None)
        return {
            "source": "szsdlc", "szsdlc_version": szsdlc.__version__,
            "parent_relation": cfg.parent_relation.name,
            "dependency_relation": dependency,
            "dependency_source": "config" if declared else ("convention" if dependency else None),
            "types": types, "relations": relations,
            "roadmaps": [{"name": n, "title": s.title, "horizons": list(s.horizons)} for n, s in cfg.roadmaps.items()],
        }

    def type_of(self, e) -> dict:
        return next(t for t in self.schema["types"] if t["prefix"] == e.type.prefix)

    # -- payloads ------------------------------------------------------------
    def info(self) -> dict:
        project = self.cfg.data.get("project") or {}
        return {
            "name": project.get("name") or (locations.store_name(self.sdlc_root) if self.relocated else self.sdlc_root.name),
            "location": locations.display(self.location) if self.remote else str(self.start),
            "update_warning": self.update_warning,
            "sdlc_root": str(self.sdlc_root),
            "sdlc_store_dir": str(self.sdlc_store_dir),
            "asset_root": str(self.asset_root) if self.asset_root else None,
            "backend": {"kind": getattr(self.backend, "type", "workdir"), "summary": self.backend.summary(),
                        "relocated": self.relocated},
            "schema_source": "szsdlc", "szsdlc_version": szsdlc.__version__,
            "entity_count": len(self.store_model),
            "duplicates": [{"id": i.text, "path": self._rel(p)} for i, p in self.store_model.duplicates],
            "unparseable": [{"path": self._rel(u.path), "error": u.error, "id": u.entity_id.text if u.entity_id else None}
                            for u in self.store_model.unparseable],
            "load_error": self.load_error,
            "readonly": True,
        }

    def progress(self, e) -> dict | None:
        p = e.progress
        if p is None:
            return None
        art = e.artifact_path(e.type.progress_artifact)
        return {"done": p.done, "total": p.total, "source": self._rel(art) if art and art.is_file() else None}

    def row(self, e) -> dict:
        key = norm_id(e.id.text)
        return jsonify({
            "id": e.id.text, "type": e.type.prefix, "title": e.title, "status": e.status, "layout": e.layout,
            "path": self._rel(e.path), "tags": e.tags, "parent": e.parent(),
            "children": len(self.children.get(key, [])), "progress": self.progress(e),
            "placement": self.placement.get(key),
            "fields": {name: e.field(name) for name in e.type.fields},
            # Authored edges only; the client derives inverses, as szsdlc does (REQ-0005).
            "relations": [[kind, target] for kind, targets in e.relations.items() for target in targets],
        })

    def rows(self) -> list[dict]:
        return [self.row(e) for e in self.store_model]

    def entity(self, ref: str) -> dict | None:
        e = self.by_key.get(norm_id(ref) or "")
        if e is None:
            return None
        key = norm_id(e.id.text)
        inverse = {r.name: r.inverse for r in self.cfg.relations.values()}
        relations = [{"direction": "out", "kind": kind, "id": target, "resolved": norm_id(target) in self.by_key}
                     for kind, targets in e.relations.items() for target in targets]
        relations += [{"direction": "in", "kind": kind, "inverse": inverse.get(kind), "id": src, "resolved": True}
                      for kind, src in self.incoming.get(key, [])]
        out = self.row(e)
        out.update({
            "dir": self._rel(e.home) if e.home else None, "body": e.body, "relations": relations,
            "children_ids": list(self.children.get(key, [])), "documents": self.documents(e),
            "derived": {name: plain(value) for name, value in self.graph.derived(e).items()},
        })
        return jsonify(out)

    def documents(self, e) -> list[dict]:
        path = self._rel(e.path)
        name = path.rsplit("/", 1)[-1]
        docs = [{"name": f"{name} § {e.id.text}" if e.layout == "section" else name, "kind": "record", "root": "sdlc",
                 "path": path, "exists": True, "size": len(e.body.encode())}]
        home = self._rel(e.home) if e.home else None
        artifacts = [self._rel(p) for p in e.artifact_files()]
        for a in artifacts:
            docs.append({"name": a[len(home) + 1:] if home else a, "kind": "artifact", "root": "sdlc", "path": a,
                         "exists": True, "size": (self.sdlc_root / a).stat().st_size})
        seen = {d["path"] for d in docs}
        sources = [(path, e.body)] + [(a, (self.sdlc_root / a).read_text(encoding="utf-8", errors="replace"))
                                      for a in artifacts if a.endswith((".md", ".markdown"))]
        for mentioned_in, text in sources:
            for ref in references(text):
                if ref.startswith(("http://", "https://")):
                    if ref not in seen:
                        seen.add(ref)
                        docs.append({"name": ref, "kind": "link", "root": "web", "url": ref, "exists": None,
                                     "mentioned_in": mentioned_in})
                    continue
                hit = self.roots.resolve(ref, mentioned_in)
                key = f"{hit['root']}:{hit['path']}"
                if key in seen or (hit["root"] == "sdlc" and hit["path"] in seen):
                    continue
                seen.add(key)
                target = self.by_path.get(hit["path"]) if hit["root"] == "sdlc" else None
                docs.append({"name": ref, "kind": "entity" if target else "reference",
                             "entity": target.id.text if target else None, "mentioned_in": mentioned_in, **hit})
        return docs

    def doc(self, root: str, rel: str, fallback: bool = False) -> dict:
        out = self.roots.read(root, rel, fallback)
        if out.get("exists") and out["root"] == "sdlc":
            target = self.by_path.get(out["path"])
            out["entity"] = target.id.text if target else None
        return out

    def _store_documents(self) -> list[dict]:
        """Generated views and records first, then any other Markdown in the project sdlc root."""
        outputs = {self._rel(self.cfg.view_path(n)) for n in self.cfg.views}
        outputs |= {self._rel(self.cfg.record_path(n)) for n in self.cfg.records}
        entity_files = {self._rel(e.path) for e in self.store_model}
        homes = tuple(self._rel(e.home) + "/" for e in self.store_model if e.home)
        docs = []
        for f in sorted(self.sdlc_root.rglob("*.md")):
            rel = self._rel(f)
            if any(part.startswith(".") or part in self.excludes for part in Path(rel).parts) or not self._owned(f):
                continue
            if rel in entity_files or rel.startswith(homes):
                continue
            text = f.read_text(encoding="utf-8", errors="replace")
            title = next((line[2:].strip() for line in text.splitlines() if line.startswith("# ")), f.stem)
            docs.append({"root": "sdlc", "path": rel, "title": title,
                         "generated": rel in outputs or GENERATED_MARK in text[:400]})
        return sorted(docs, key=lambda d: (not d["generated"], d["path"]))

    # -- static export -------------------------------------------------------
    def snapshot(self) -> dict:
        """Everything the frontend asks for, precomputed, with no local paths in it."""
        docs = {}
        for f in sorted(self.sdlc_root.rglob("*")):
            rel = Path(self._rel(f))
            if (f.is_file() and f.suffix.lower() in (".md", ".markdown", ".yml", ".yaml") and self._owned(f)
                    and not any((part.startswith(".") and part != ".szsdlc") or part in self.excludes for part in rel.parts)):
                docs[f"sdlc:{rel.as_posix()}"] = self.doc("sdlc", rel.as_posix())
        details = {e.id.text: self.entity(e.id.text) for e in self.store_model}
        for detail in details.values():  # asset-root documents the items actually reference
            for d in detail["documents"]:
                if d.get("root") == "assets" and d.get("exists"):
                    docs.setdefault(f"assets:{d['path']}", self.doc("assets", d["path"]))
        info = {**self.info(), "sdlc_root": self.sdlc_root.name, "sdlc_store_dir": self.sdlc_store_dir.name,
                "asset_root": self.asset_root.name if self.asset_root else None}
        if not self.remote:  # a remote location is already fit to show; a local one is a path on this machine
            info["location"] = self.start.name
        return {"generated_at": _dt.date.today().isoformat(), "project": info, "schema": self.schema,
                "entities": self.rows(), "details": details, "roadmaps": self.roadmaps,
                "docs_list": self.store_docs, "docs": docs}
